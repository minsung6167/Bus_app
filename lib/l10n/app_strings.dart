  static String get(String langCode, String key) =>
      _data[langCode]?[key] ?? _data['ko']![key] ?? key;

  /// {n}, {id}, {seat}, {type} 등 플레이스홀더 치환
  static String fmt(String langCode, String key, Map<String, String> args) {
    var s = get(langCode, key);
    for (final e in args.entries) {
      s = s.replaceAll('{${e.key}}', e.value);
    }
    return s;
  }

  static String dateFormat(String langCode) {
    switch (langCode) {
      case 'en':
        return 'MMM d, yyyy';
      case 'zh':
      case 'ja':
        return 'yyyy年M月d日';
      default:
        return 'yyyy년 M월 d일';
    }
  }
